//! Holds host/abi.zig to roc glue's layout of the platform, at compile time.
//! Each C function glue declares for the platform (the app's entries) is
//! held to abi.zig's function of that symbol, argument by argument and the
//! answer: a record field by field by name (its offset, and what it holds,
//! down through records, unions and lists), a list by its element, a tag
//! union's tags by number, a number by its type. Two same-sized fields
//! swapped pass a size check and fail here, naming the function, the field
//! and both offsets. A function either side has and the other has not
//! fails the build. glue/platform_abi.zig is glue's output, regenerated by
//! `shale tools/glue.shale` after a change to platform/.
//!
//! The checker is roc-chat's `host/seam_test.zig`, with unions added,
//! because this seam's tag unions carry payloads.

const std = @import("std");
const abi = @import("abi.zig");
const glue = @import("glue/platform_abi.zig");

/// The runtime's functions, which the host exports and glue declares as the
/// host's to give; they are not part of the platform's own seam.
const runtime = [_][]const u8{ "roc_alloc", "roc_dealloc", "roc_realloc", "roc_dbg", "roc_expect_failed", "roc_crashed" };

/// The seam's symbols in `M`: each `pub` C function but the runtime's.
fn seamNames(comptime M: type) []const []const u8 {
    comptime {
        @setEvalBranchQuota(200_000);
        var names: []const []const u8 = &.{};
        for (@typeInfo(M).@"struct".decl_names) |n| {
            const T = @TypeOf(@field(M, n));
            if (@typeInfo(T) != .@"fn") continue;
            if (@typeInfo(T).@"fn".attrs.@"callconv".eql(.c) and !has(&runtime, n)) names = names ++ &[_][]const u8{n};
        }
        return names;
    }
}

const glue_names = seamNames(glue);
const abi_names = seamNames(abi);

fn has(comptime names: []const []const u8, comptime name: []const u8) bool {
    for (names) |n| if (std.mem.eql(u8, n, name)) return true;
    return false;
}

/// Why abi.zig's `Want` is not laid out as roc glue's `Got`, at `at` (a path
/// from the function: `.field`, `[]` for a list's element), or null when
/// they agree.
fn mismatch(comptime Want: type, comptime Got: type, comptime at: []const u8) ?[]const u8 {
    @setEvalBranchQuota(1_000_000);
    return switch (@typeInfo(Got)) {
        .@"struct" => if (@hasField(Got, "elements_ptr"))
            listMismatch(Want, Got, at)
        else
            recordMismatch(Want, Got, at),
        .@"union" => unionMismatch(Want, Got, at),
        .@"enum" => tagsMismatch(Want, Got, at),
        else => if (Want == Got) null else at ++ ": " ++ @typeName(Want) ++ " in abi.zig, " ++ @typeName(Got) ++ " in roc glue",
    };
}

/// A Roc list as abi.zig lays one out: an extern struct of three words, the
/// elements' pointer, the length and the capacity.
fn isList(comptime T: type) bool {
    const info = @typeInfo(T);
    if (info != .@"struct" or info.@"struct".layout != .@"extern") return false;
    const s = info.@"struct";
    if (s.field_names.len != 3) return false;
    const P = s.field_types[0];
    if (@typeInfo(P) != .optional or @typeInfo(@typeInfo(P).optional.child) != .pointer) return false;
    return std.mem.eql(u8, s.field_names[1], "length") and s.field_types[1] == usize and
        std.mem.eql(u8, s.field_names[2], "capacity_or_alloc_ptr") and s.field_types[2] == usize;
}

fn elementOf(comptime L: type) type {
    return @typeInfo(@typeInfo(@typeInfo(L).@"struct".field_types[0]).optional.child).pointer.child;
}

fn listMismatch(comptime Want: type, comptime Got: type, comptime at: []const u8) ?[]const u8 {
    if (!isList(Want)) return at ++ ": a List in roc glue, " ++ @typeName(Want) ++ " in abi.zig";
    if (@sizeOf(Want) != @sizeOf(Got) or @offsetOf(Want, "length") != @offsetOf(Got, "length") or
        @offsetOf(Want, "capacity_or_alloc_ptr") != @offsetOf(Got, "capacity_or_alloc_ptr"))
        return at ++ ": " ++ @typeName(Want) ++ " is no list as roc glue lays one out";
    return mismatch(elementOf(Want), elementOf(Got), at ++ "[]");
}

fn recordMismatch(comptime Want: type, comptime Got: type, comptime at: []const u8) ?[]const u8 {
    const info = @typeInfo(Want);
    if (info != .@"struct" or info.@"struct".layout != .@"extern")
        return at ++ ": a record in roc glue, " ++ @typeName(Want) ++ " in abi.zig, no extern struct";
    const got = @typeInfo(Got).@"struct";
    for (got.field_names, got.field_types) |name, G| {
        const here = at ++ "." ++ name;
        if (!@hasField(Want, name)) return here ++ ": in roc glue, not in " ++ @typeName(Want);
        if (@offsetOf(Want, name) != @offsetOf(Got, name)) return std.fmt.comptimePrint(
            "{s}: at byte {d} of {s}, at byte {d} in roc glue",
            .{ here, @offsetOf(Want, name), @typeName(Want), @offsetOf(Got, name) },
        );
        if (mismatch(@FieldType(Want, name), G, here)) |m| return m;
    }
    for (info.@"struct".field_names) |name| {
        if (!@hasField(Got, name)) return at ++ "." ++ name ++ ": in " ++ @typeName(Want) ++ ", not in roc glue";
    }
    return sizeMismatch(Want, Got, at);
}

/// A tag union's payload: every member by name, each at offset 0.
fn unionMismatch(comptime Want: type, comptime Got: type, comptime at: []const u8) ?[]const u8 {
    const info = @typeInfo(Want);
    if (info != .@"union" or info.@"union".layout != .@"extern")
        return at ++ ": a payload union in roc glue, " ++ @typeName(Want) ++ " in abi.zig, no extern union";
    const got = @typeInfo(Got).@"union";
    for (got.field_names, got.field_types) |name, G| {
        if (!@hasField(Want, name)) return at ++ "." ++ name ++ ": in roc glue, not in " ++ @typeName(Want);
        if (mismatch(@FieldType(Want, name), G, at ++ "." ++ name)) |m| return m;
    }
    if (info.@"union".field_names.len != got.field_names.len)
        return at ++ ": " ++ @typeName(Want) ++ " has members roc glue has not";
    return sizeMismatch(Want, Got, at);
}

fn sizeMismatch(comptime Want: type, comptime Got: type, comptime at: []const u8) ?[]const u8 {
    if (@sizeOf(Want) == @sizeOf(Got) and @alignOf(Want) == @alignOf(Got)) return null;
    return std.fmt.comptimePrint(
        "{s}: {s} is {d} bytes aligned to {d}, roc glue's {d} aligned to {d}",
        .{ at, @typeName(Want), @sizeOf(Want), @alignOf(Want), @sizeOf(Got), @alignOf(Got) },
    );
}

/// The tag of `Want` that is Roc's tag `glue_name`, the names matched
/// without case or underscores.
fn tagNamed(comptime Want: type, comptime glue_name: []const u8) ?[:0]const u8 {
    for (@typeInfo(Want).@"enum".field_names) |name| {
        if (std.mem.eql(u8, bare(name), bare(glue_name))) return name;
    }
    return null;
}

fn bare(comptime name: []const u8) []const u8 {
    var out: []const u8 = "";
    for (name) |c| {
        if (c != '_') out = out ++ &[_]u8{std.ascii.toLower(c)};
    }
    return out;
}

fn tagsMismatch(comptime Want: type, comptime Got: type, comptime at: []const u8) ?[]const u8 {
    if (@typeInfo(Want) != .@"enum") return at ++ ": tags in roc glue, " ++ @typeName(Want) ++ " in abi.zig";
    if (@sizeOf(Want) != @sizeOf(Got)) return at ++ ": " ++ @typeName(Want) ++ " is not roc glue's size";
    const got = @typeInfo(Got).@"enum";
    for (got.field_names, got.field_values) |glue_name, value| {
        const name = tagNamed(Want, glue_name) orelse
            return at ++ ": the tag `" ++ glue_name ++ "` is roc glue's, not " ++ @typeName(Want) ++ "'s";
        if (@backingInt(@field(Want, name)) != value) return std.fmt.comptimePrint(
            "{s}: the tag `{s}` is {d} in {s}, {d} in roc glue",
            .{ at, name, @backingInt(@field(Want, name)), @typeName(Want), value },
        );
    }
    if (@typeInfo(Want).@"enum".field_names.len != got.field_names.len)
        return at ++ ": " ++ @typeName(Want) ++ " has tags roc glue has not";
    return null;
}

/// Symbol `name`'s two declarations, argument by argument, then the answer.
fn fnMismatch(comptime name: []const u8) ?[]const u8 {
    if (!@hasDecl(abi, name)) return name ++ ": roc glue declares it, abi.zig has no `pub` function of the name";
    const want = @typeInfo(@TypeOf(@field(abi, name))).@"fn";
    const got = @typeInfo(@TypeOf(@field(glue, name))).@"fn";
    if (want.param_types.len != got.param_types.len) return std.fmt.comptimePrint(
        "{s}: {d} arguments in abi.zig, {d} in roc glue",
        .{ name, want.param_types.len, got.param_types.len },
    );
    for (want.param_types, got.param_types, 0..) |W, G, i| {
        if (mismatch(W.?, G.?, std.fmt.comptimePrint("{s} argument {d}", .{ name, i }))) |m| return m;
    }
    return mismatch(want.return_type.?, got.return_type.?, name ++ "'s answer");
}

comptime {
    @setEvalBranchQuota(1_000_000);
    for (abi_names) |n| {
        if (!has(glue_names, n)) @compileError(n ++ ": abi.zig has it, the roc glue snapshot has not; regenerate it: shale tools/glue.shale");
    }
    for (glue_names) |n| {
        if (fnMismatch(n)) |m| @compileError("roc glue lays the seam out unlike abi.zig: " ++ m);
    }
}

fn answerOf(comptime f: anytype) type {
    return @typeInfo(@TypeOf(f)).@"fn".return_type.?;
}

fn contains(haystack: []const u8, needle: []const u8) bool {
    return std.mem.indexOf(u8, haystack, needle) != null;
}

test "roc glue declares every entry abi.zig has, and no other: eight" {
    try std.testing.expectEqual(abi_names.len, glue_names.len);
    try std.testing.expectEqual(8, abi_names.len);
}

test "the frame's layout: a shape is 80 bytes with its tag at 72, a fill 44 with its tag at 40" {
    try std.testing.expectEqual(56, @sizeOf(abi.Frame));
    try std.testing.expectEqual(80, @sizeOf(abi.Shape));
    try std.testing.expectEqual(72, @offsetOf(abi.Shape, "tag"));
    try std.testing.expectEqual(44, @sizeOf(abi.Fill));
    try std.testing.expectEqual(40, @offsetOf(abi.Fill, "tag"));
    try std.testing.expectEqual(16, @sizeOf(abi.Sun));
}

test "the step's keys are held then struck, and the two swapped fail the check" {
    try std.testing.expectEqual(0, @offsetOf(abi.Keys, "held"));
    try std.testing.expectEqual(4, @offsetOf(abi.Keys, "struck"));
    try std.testing.expect(comptime fnMismatch("roc_step") == null);
    const Swapped = extern struct { struck: u32, held: u32 };
    const m = comptime mismatch(Swapped, glue.Step_for_hostArg2, "roc_step argument 2").?;
    try std.testing.expect(contains(m, "roc_step argument 2.held: at byte 4 of "));
    try std.testing.expect(contains(m, "at byte 0 in roc glue"));
}

test "a swap, a renumbered tag and a missing member each fail the check, named" {
    // A linear gradient's two stops exchanged: the same size, the wrong offsets.
    const Swapped = extern struct { start: abi.Stop, from: abi.Point, end: abi.Stop, to: abi.Point };
    const m = comptime mismatch(Swapped, glue.EllipticalOrLinearOrRadialOrRoundOrSolidLinear, "linear").?;
    try std.testing.expect(contains(m, "linear.end: at byte 16 of "));
    try std.testing.expect(contains(m, "at byte 0 in roc glue"));
    // The fills numbered in the source's order rather than alphabetically.
    const Renumbered = enum(u8) { solid, round, radial, linear, elliptical };
    const t = comptime mismatch(Renumbered, glue.EllipticalOrLinearOrRadialOrRoundOrSolidTag, "fill").?;
    try std.testing.expect(contains(t, "the tag `elliptical` is 4 in "));
    // A payload union without the disc.
    const NoDisc = extern union { polygon: abi.Polygon };
    const u = comptime mismatch(NoDisc, glue.DiscOrPolygonPayload, "shape").?;
    try std.testing.expect(contains(u, "shape.disc: in roc glue, not in "));
    // The same layout passes.
    try std.testing.expect(comptime mismatch(abi.Linear, glue.EllipticalOrLinearOrRadialOrRoundOrSolidLinear, "linear") == null);
}
